# THE PROBLEM
"""
15-20% revenue leakage through under-recorded billable hours = P3.3-4.4M per year unrecovered.
No profitability visibility per client, per matter, or per partner.
Top 10 clients = 65% of all fee income = catastrophic concentration risk.
No early warning system for client disengagement.

PROBLEM 1 - TIME RECORDING CULTURE
  Associates view time recording as administrative overhead.
  Hours are worked but not put on the billing system. Those hours are never invoiced.
  The firm absorbs the cost of the work with zero revenue return.
  Employment Law has the worst recording rate (Partner Mmolawa's portfolio).

PROBLEM 2 - NO PROFITABILITY VISIBILITY
  The billing system captures invoiced amounts but never connects them to
  recorded time and matter costs to produce a per-client or per-matter margin.
  Partners cannot tell which clients are profitable and which are not.

PROBLEM 3 - CLIENT CONCENTRATION
  Top 10 clients = 65% of fee income. If two major clients leave, the firm
  must replace over 10% of annual revenue — a significant challenge in a
  relationship-driven legal market where acquisition takes years.
"""

